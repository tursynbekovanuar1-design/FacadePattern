package subsystem;

public class PopcornPopper {
    public void on() {
        System.out.println("Аппарат для попкорна включен.");
    }

    public void off() {
        System.out.println("Аппарат для попкорна выключен.");
    }

    public void pop() {
        System.out.println("Аппарат готовит попкорн! 🍿");
    }
}