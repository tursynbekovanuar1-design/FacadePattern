package subsystem;

public class Projector {
    public void on() {
        System.out.println("Проектор включен.");
    }

    public void off() {
        System.out.println("Проектор выключен.");
    }

    public void wideScreenMode() {
        System.out.println("Проектор переведен в широкоэкранный режим (16:9).");
    }
}